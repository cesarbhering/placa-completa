import { aplicarCupom, type PlanoId } from '../../shared/planos'
import { precoDoPlano, type BracoPreco } from '../../shared/ab-preco'
import { cancelarPaymentIntent, lerPaymentIntent, type EstadoPaymentIntent } from './stripe'

// Validacao + calculo de cupom (v1). Usado tanto pelo endpoint de validar
// (blur do input, so pra mostrar o preco) quanto pelo checkout (que RECALCULA
// tudo de novo antes de gravar o pedido — nunca confia no preco que o client
// mandou, mesmo que tenha vindo desta mesma funcao segundos antes).
//
// Falha SEMPRE fechada: qualquer motivo de recusa devolve ok:false com um
// motivo, nunca deixa passar por omissao.

export interface CupomValidado {
  ok: boolean
  motivo?: string
  cupomId?: string
  precoBrutoCentavos: number
  descontoCentavos: number
  precoLiquidoCentavos: number
  /**
   * true = cupom pessoal validado sem e-mail (prefill pelo link do e-mail).
   * O desconto ja aparece, mas so vale mesmo pra quem digitar o e-mail certo,
   * e o checkout final revalida com o e-mail antes de cobrar.
   */
  exigeEmail?: boolean
  /** true = este cupom pode zerar o preco (bypass do Pix), se o desconto cobrir tudo. */
  permiteGratis?: boolean
  limiteUsoPorCliente?: number | null
  /** 'recompra' = cupom gerado por uma compra (vai pro pedido como cupom_recompra). */
  origem?: string | null
  /** Pedido que gerou o cupom de recompra (mede compartilhamento). */
  pedidoOrigemId?: string | null
  /**
   * true = this refusal looks like a guess (unknown, inactive, not yet valid or
   * expired code, other plan, other e-mail) and counts toward the attempt limits
   * in server/utils/cupom-limite.ts. Internal: never sent to the browser.
   */
  contaTentativa?: boolean
  /** true = personal coupon (email_restrito) matched against the e-mail sent. Internal. */
  pessoal?: boolean
  /** true = refused right after the lookup because only our coupons are accepted now. Internal. */
  foraDoSistema?: boolean
  /** true = personal coupon refused because the e-mail sent is not its owner's. Internal. */
  outroEmail?: boolean
}

/** cupons_premium.origem values of coupons generated by the system (accepted under the global coupon limit). */
export const ORIGENS_CUPOM_SISTEMA = ['recompra', 'bump', 'pix_recover', 'gratis_recover']

/**
 * "07/09 as 18h30". Fuso de Brasilia fixo: o prazo do cupom e o prazo que o
 * e-mail prometeu, e o e-mail foi escrito no horario daqui, nao no do celular
 * de quem viajou.
 */
function formatarVencimento(iso: string): string {
  const d = new Date(iso)
  const partes = new Intl.DateTimeFormat('pt-BR', {
    timeZone: 'America/Sao_Paulo', day: '2-digit', month: '2-digit', hour: '2-digit', minute: '2-digit', hour12: false,
  }).formatToParts(d)
  const g = (t: string) => partes.find(p => p.type === t)?.value || ''
  return `${g('day')}/${g('month')} as ${g('hour')}h${g('minute')}`
}

export async function validarCupom(
  supabase: ReturnType<typeof usePremiumSupabase>,
  codigoBruto: string,
  plano: PlanoId,
  // Opcional: na validacao previa (pessoa digitou o cupom antes do e-mail) o
  // limite por cliente e simplesmente pulado. O checkout final SEMPRE chama
  // esta funcao com o e-mail, entao a regra continua valendo onde importa.
  email?: string,
  // Price A/B arm of the order (shared/ab-preco.ts). The coupon applies to the
  // price the visitor was shown; null/'A' = table price.
  braco?: BracoPreco | null,
  // somenteDoSistema (global coupon limit on, server/utils/cupom-limite.ts):
  // right after the lookup, refuse anything that is not ours, with no further
  // queries, so an unknown code and a paused campaign cost the same work.
  opcoes: { somenteDoSistema?: boolean } = {},
): Promise<CupomValidado> {
  const precoBrutoCentavos = plano === 'basica' || plano === 'completa' ? precoDoPlano(plano, braco) : 0
  const semDesconto = { ok: false as const, precoBrutoCentavos, descontoCentavos: 0, precoLiquidoCentavos: precoBrutoCentavos }

  if (plano !== 'basica' && plano !== 'completa') {
    return { ...semDesconto, motivo: 'Plano invalido para cupom.' }
  }

  const codigo = codigoBruto.trim().toUpperCase().replace(/\s+/g, '')
  if (!codigo) return { ...semDesconto, motivo: 'Informe um cupom.' }

  const { data: cupom, error } = await supabase
    .from('cupons_premium')
    .select('*')
    .eq('codigo', codigo)
    .maybeSingle()

  // A database error is our failure, not a guess: it does not count.
  if (error) return { ...semDesconto, motivo: 'Cupom nao encontrado.' }
  if (!cupom) return { ...semDesconto, motivo: 'Cupom nao encontrado.', contaTentativa: true }
  if (opcoes.somenteDoSistema && !ORIGENS_CUPOM_SISTEMA.includes(String(cupom.origem || '')) && !cupom.email_restrito) {
    return { ...semDesconto, motivo: 'Cupom nao encontrado.', foraDoSistema: true }
  }
  if (!cupom.ativo) return { ...semDesconto, motivo: 'Cupom inativo.', contaTentativa: true }

  const agora = Date.now()
  if (cupom.valido_de && new Date(cupom.valido_de).getTime() > agora) {
    return { ...semDesconto, motivo: 'Cupom ainda nao esta valido.', contaTentativa: true }
  }
  if (cupom.valido_ate && new Date(cupom.valido_ate).getTime() < agora) {
    // Vencido merece data e hora, nao um "invalido" generico: o cupom de
    // recuperacao dura 24 horas e quem chega 10 minutos tarde precisa entender
    // que perdeu o prazo, nao achar que digitou errado.
    return { ...semDesconto, motivo: `Este cupom venceu em ${formatarVencimento(cupom.valido_ate)}.`, contaTentativa: true }
  }
  if (!Array.isArray(cupom.planos) || !cupom.planos.includes(plano)) {
    return { ...semDesconto, motivo: 'Cupom nao vale para este plano.', contaTentativa: true }
  }

  // Cupom pessoal (recuperacao de Pix abandonado): vale so pra quem recebeu.
  // Sem isto, o codigo do e-mail de uma pessoa viraria desconto pra qualquer um
  // que o repassasse. Comparacao sem caixa: quem digita o proprio e-mail no
  // checkout escreve como quiser.
  let exigeEmail = false
  if (cupom.email_restrito) {
    // Sem e-mail ainda (o link do e-mail abre o checkout com o cupom pronto,
    // antes de a pessoa digitar qualquer coisa): mostra o desconto e avisa que
    // ele depende do e-mail. Nao e brecha: o checkout SEMPRE revalida com o
    // e-mail preenchido, e la a regra abaixo derruba quem nao for o dono.
    if (!email) exigeEmail = true
    else if (String(cupom.email_restrito).trim().toLowerCase() !== email.trim().toLowerCase()) {
      // Nunca revelar QUAL e-mail: o codigo pode ter sido repassado, e o
      // destinatario original nao autorizou ninguem a descobrir o e-mail dele.
      return { ...semDesconto, motivo: 'Este cupom e pessoal e vale so para o e-mail que o recebeu.', contaTentativa: true, outroEmail: true }
    }
  }


  // Limite global e por-cliente contados na tabela de usos (fonte da verdade),
  // nao no contador `usos_atual` (que e so um cache pra leitura rapida no
  // dashboard e pode ficar defasado sem quebrar a regra de negocio).
  if (cupom.limite_uso_global != null) {
    if ((await usosQueContam(supabase, cupom.id, {}, cupom.limite_uso_global)) >= cupom.limite_uso_global) {
      // Cupom de uso unico ja gasto: a pessoa precisa saber que ele funcionou
      // uma vez, senao tenta de novo achando que e erro do site.
      return { ...semDesconto, motivo: cupom.limite_uso_global === 1 ? 'Este cupom ja foi utilizado.' : 'Cupom esgotado.' }
    }
  }
  if (cupom.limite_uso_por_cliente != null && email) {
    if ((await usosQueContam(supabase, cupom.id, { email }, cupom.limite_uso_por_cliente)) >= cupom.limite_uso_por_cliente) {
      return { ...semDesconto, motivo: 'Este cupom ja foi utilizado.' }
    }
  }

  const regra = {
    tipo: cupom.tipo,
    valor: cupom.valor,
    planos: cupom.planos,
    permiteGratis: !!cupom.permite_gratis,
  }
  let { precoBrutoCentavos: bruto, descontoCentavos, precoLiquidoCentavos } = aplicarCupom(plano, regra, precoBrutoCentavos)
  // The second-plate offer (cupom_bump) promises a fixed final price (its fixed
  // discount was sized on the table price). In any arm it must land on that
  // promised price, and bruto/desconto must be relative to the ARM price: the
  // checkout screen shows arm price - desconto, so shown = charged.
  if (cupom.origem === 'bump') {
    precoLiquidoCentavos = aplicarCupom(plano, regra, precoDoPlano(plano, null)).precoLiquidoCentavos
    bruto = precoBrutoCentavos
    descontoCentavos = Math.max(0, bruto - precoLiquidoCentavos)
    precoLiquidoCentavos = bruto - descontoCentavos
  }

  return {
    ok: true,
    origem: cupom.origem ?? null,
    pedidoOrigemId: cupom.pedido_origem_id ?? null,
    cupomId: cupom.id,
    precoBrutoCentavos: bruto,
    descontoCentavos,
    precoLiquidoCentavos,
    exigeEmail,
    pessoal: !!(cupom.email_restrito && email),
    permiteGratis: !!cupom.permite_gratis,
    limiteUsoPorCliente: cupom.limite_uso_por_cliente,
  }
}

/**
 * A card attempt opened this long ago that never charged counts as abandoned
 * (3DS window closed, page left on the amount warning).
 */
const CARTAO_ABANDONADO_MS = 30 * 60_000
/** Card attempts checked at Stripe per validation, at most. */
const MAX_TENTATIVAS_CONFERIDAS = 3

type FiltroUsos = { email?: string }

/**
 * Card attempt that will never be paid: canceled, declined (or 3DS failed), or
 * opened over 30 min ago without a charge. Paid, processing and in-progress
 * attempts (3DS open, intent waiting for the next click) are alive.
 */
function tentativaCartaoMorta(pi: EstadoPaymentIntent, criadoEm: string | null | undefined, agora = Date.now()): boolean {
  if (pi.status === 'canceled') return true
  const velha = !!criadoEm && agora - new Date(criadoEm).getTime() > CARTAO_ABANDONADO_MS
  if (pi.status === 'requires_payment_method') return pi.falhou || velha
  if (pi.status === 'requires_action' || pi.status === 'requires_confirmation') return velha
  return false
}

/**
 * Uses that count against a coupon limit. A released use (liberado_em) does
 * not. At the limit, card attempts that will never be paid are released first.
 * Without the liberado_em column (migration not applied yet) every use counts
 * and nothing is released, as before.
 */
async function usosQueContam(supabase: any, cupomId: string, filtro: FiltroUsos, limite: number): Promise<number> {
  const contar = () => {
    const q = supabase.from('cupons_premium_usos').select('id', { count: 'exact', head: true }).eq('cupom_id', cupomId)
    return filtro.email ? q.eq('email', filtro.email) : q
  }
  const { count, error } = await contar().is('liberado_em', null)
  if (error) return (await contar()).count || 0
  const usos = count || 0
  if (usos < limite) return usos
  return usos - (await liberarTentativasMortas(supabase, cupomId, filtro, usos - limite + 1))
}

/**
 * Releases up to `quantas` uses held by card attempts that will never be paid.
 * The PaymentIntent is canceled at Stripe BEFORE the use is marked, so that
 * order can never be paid with the coupon afterwards. Stripe silent or the
 * cancel refused: the use keeps counting. Pix orders are left out: an unpaid
 * one can still get a new Pix at the same price (renovar-pix).
 */
async function liberarTentativasMortas(supabase: any, cupomId: string, filtro: FiltroUsos, quantas: number): Promise<number> {
  const base = supabase
    .from('cupons_premium_usos')
    .select('id, pedidos_premium!inner(stripe_session_id, criado_em)')
    .eq('cupom_id', cupomId)
    .is('liberado_em', null)
    .eq('pedidos_premium.forma_pagamento', 'cartao')
    .eq('pedidos_premium.status', 'aguardando_pagamento')
  const { data, error } = await (filtro.email ? base.eq('email', filtro.email) : base).limit(MAX_TENTATIVAS_CONFERIDAS)
  if (error || !Array.isArray(data)) return 0
  let liberados = 0
  for (const uso of data) {
    if (liberados >= quantas) break
    const pedido = Array.isArray(uso.pedidos_premium) ? uso.pedidos_premium[0] : uso.pedidos_premium
    const piId = String(pedido?.stripe_session_id || '')
    // Card Elements orders keep the intent id; the old hosted checkout kept a session id.
    if (!piId.startsWith('pi_')) continue
    const pi = await lerPaymentIntent(piId)
    if (!pi || !tentativaCartaoMorta(pi, pedido?.criado_em)) continue
    if (pi.status !== 'canceled' && !(await cancelarPaymentIntent(piId))) continue
    const { data: marcados } = await supabase
      .from('cupons_premium_usos')
      .update({ liberado_em: new Date().toISOString() })
      .eq('id', uso.id)
      .is('liberado_em', null)
      .select('id')
    if (!Array.isArray(marcados) || !marcados.length) continue
    liberados++
    console.log(`[cupom] uso liberado: tentativa de cartao que nao vai ser paga (${pi.status})`)
    // Same usos_atual cache decrement the free path uses.
    await liberarUsoCupomGratis(supabase, cupomId)
  }
  return liberados
}

/**
 * SO pro caminho gratis (preco liquido = 0): reivindica atomicamente 1 uso do
 * cupom via RPC que trava a linha do cupom (evita corrida — sem isso, duas
 * requisicoes concorrentes podiam ler o mesmo contador e as duas passarem, e
 * cada resgate da completa custa ~R$5 de SERPRO real). Chamar ANTES de criar
 * o pedido; se devolver false, NAO libera o relatorio de graca (cai pro preco
 * cheio, tratado por quem chamou).
 */
export async function reivindicarUsoCupomGratis(
  supabase: ReturnType<typeof usePremiumSupabase>,
  cupomId: string,
  email: string,
  limitePorCliente: number | null | undefined,
): Promise<boolean> {
  const { data, error } = await supabase.rpc('reivindicar_uso_cupom_gratis', {
    p_cupom_id: cupomId,
    p_email: email,
    p_limite_por_cliente: limitePorCliente ?? null,
  })
  if (error) {
    console.warn('[cupom] reivindicar uso gratis falhou:', error.message)
    return false
  }
  return !!data
}

/** Contrapartida do reivindicar: solta a vaga se o pedido nao puder ser criado depois. */
export async function liberarUsoCupomGratis(
  supabase: ReturnType<typeof usePremiumSupabase>,
  cupomId: string,
): Promise<void> {
  try {
    await supabase.rpc('liberar_uso_cupom_gratis', { p_cupom_id: cupomId })
  } catch (e: any) {
    console.warn('[cupom] liberar uso gratis falhou:', e?.message)
  }
}

// Registra o uso (chamado SO pelo checkout, apos criar o pedido). pedido_id e
// UNIQUE na tabela: se o checkout for chamado 2x pro mesmo pedido (retry),
// o segundo insert falha e e ignorado — sem double-count no P&L.
export async function registrarUsoCupom(
  supabase: ReturnType<typeof usePremiumSupabase>,
  opts: {
    cupomId: string
    pedidoId: string
    /** null = cupom de recompra usado sem e-mail. */
    email: string | null
    precoBrutoCentavos: number
    descontoCentavos: number
    precoLiquidoCentavos: number
    /**
     * true quando reivindicarUsoCupomGratis() ja incrementou usos_atual pra
     * este uso (caminho gratis) — evita contar 2x. false/omitido = caminho
     * normal (pago com desconto), incrementa aqui mesmo (best-effort).
     */
    jaReivindicado?: boolean
  },
): Promise<void> {
  try {
    await supabase.from('cupons_premium_usos').insert({
      cupom_id: opts.cupomId,
      pedido_id: opts.pedidoId,
      email: opts.email || null,
      preco_bruto: opts.precoBrutoCentavos,
      valor_desconto: opts.descontoCentavos,
      preco_liquido: opts.precoLiquidoCentavos,
    })
    if (opts.jaReivindicado) return
    // Contador best-effort pro dashboard; nao e a fonte da verdade (validarCupom
    // sempre conta a tabela de usos), entao a leve race aqui (read-then-write,
    // sem lock) nao afeta nenhuma regra de negocio, so a exibicao do numero.
    const { data: atual } = await supabase
      .from('cupons_premium')
      .select('usos_atual')
      .eq('id', opts.cupomId)
      .maybeSingle()
    await supabase
      .from('cupons_premium')
      .update({ usos_atual: (atual?.usos_atual || 0) + 1, updated_at: new Date().toISOString() })
      .eq('id', opts.cupomId)
  } catch (e: any) {
    console.warn('[cupom] registrar uso falhou:', e?.message)
  }
}
