export function aplicarWmiMundo() {
  const del = db.prepare('DELETE FROM wmi_mundo')
  const ins = db.prepare('INSERT INTO wmi_mundo (code, display_name, country, fonte) VALUES (?, ?, ?, ?)')
  const run = db.transaction(() => {
    del.run()
    for (const [code, nome, fonte] of WMI_MUNDO) ins.run(code, nome, paisPorFaixaWmi(code), fonte)
  })
  run()
  db.prepare("INSERT INTO meta (chave, valor) VALUES ('wmi_mundo_versao', ?) ON CONFLICT(chave) DO UPDATE SET valor = excluded.valor")
    .run(String(WMI_MUNDO_VERSAO))
  return WMI_MUNDO.length
}

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log(`${aplicarWmiMundo()} WMI(s) do mundo aplicado(s), versao ${WMI_MUNDO_VERSAO}.`)
}
